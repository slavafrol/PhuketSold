import { spawn } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { homedir } from 'node:os';

export const root = fileURLToPath(new URL('../../', import.meta.url));
export const apiProject = resolve(root, 'backend/PhuketSold.Api');
export const secretsFile = resolve(homedir(), '.microsoft/usersecrets/phuketsold-api-local/secrets.json');
export const login = 'phuketsold_catalog_local';
export const psqlArgs = ['exec', '-i', 'supabase_db_phuketsold', 'psql', '-X', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'];

export function run(command, args, input, env = process.env) {
  return new Promise((accept, reject) => {
    const child = spawn(command, args, { cwd: root, env, stdio: ['pipe', 'pipe', 'pipe'] });
    let stdout = '';
    child.stdout.setEncoding('utf8').on('data', chunk => { stdout = (stdout + chunk).slice(-262144); });
    // Commands may echo credentials or SQL on failure. Do not relay stderr.
    child.stderr.resume();
    child.once('error', () => reject(new Error(`${command} could not start.`)));
    child.stdin.on('error', error => { if (error.code !== 'EPIPE') reject(new Error(`${command} input failed.`)); });
    child.once('close', code => {
      if (code === 0) accept(stdout);
      else {
        const error = new Error(`${command} failed (${code}); output suppressed to protect local credentials.`);
        error.stdout = stdout;
        reject(error);
      }
    });
    child.stdin.end(input);
  });
}

export async function checkLocalDatabase() {
  if (process.argv.length > 2) throw new Error('This command accepts no target/connection arguments.');
  const context = process.env.DOCKER_CONTEXT;
  const endpoint = !context && process.env.DOCKER_HOST ? process.env.DOCKER_HOST :
    (await run('docker', ['context', 'inspect', ...(context ? [context] : []), '--format', '{{.Endpoints.docker.Host}}'])).trim();
  if (!endpoint.startsWith('unix://')) throw new Error('Only a local Docker Unix socket is allowed.');
  const version = (await run('docker', [...psqlArgs, '-Atc', 'show server_version;'])).trim();
  if (version.split(' ')[0] !== '17.11') throw new Error('Local PostgreSQL 17.11 is required. Run npm run db:check first.');
  const ports = JSON.parse(await run('docker', ['inspect', 'supabase_db_phuketsold', '--format', '{{json .NetworkSettings.Ports}}']));
  if (!ports['5432/tcp']?.some(port => port.HostPort === '54322')) throw new Error('Expected local database port 54322.');
}

export async function readSecrets() {
  try { return JSON.parse((await readFile(secretsFile, 'utf8')).replace(/^\uFEFF/, '')); }
  catch (error) { if (error.code === 'ENOENT') return {}; throw new Error('Unable to read local .NET user-secrets.'); }
}

export function localConnection(secrets) {
  const value = secrets['ConnectionStrings:Marketplace'];
  // Only accept the format generated by setup. Never forward a hosted target to
  // test processes or accidentally reuse a production secret on this workstation.
  if (typeof value !== 'string' || !/^Host=127\.0\.0\.1;Port=54322;Database=postgres;Username=phuketsold_catalog_local;Password=[a-f0-9]{64};Timeout=5;Maximum Pool Size=20;Application Name=PhuketSold\.Api$/.test(value))
    throw new Error('Missing or unexpected local catalog connection; run npm run api:db:setup.');
  return value;
}
